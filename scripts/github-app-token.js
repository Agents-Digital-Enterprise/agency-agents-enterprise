#!/usr/bin/env node
/**
 * github-app-token.js
 *
 * Generates a GitHub App installation token and injects it into ALL consumer
 * configs so every channel uses the same fresh token without any CLI auth flow:
 *
 *   .secrets/.env                  — GITHUB_TOKEN, expiry, IDs
 *   .secrets/mcp-servers.json      — MCP server block with live token
 *   ~/.config/gh/hosts.yml         — gh CLI config (written directly, no gh command)
 *
 * Usage:
 *   node scripts/github-app-token.js [installation_id]
 *
 *   --check    Exit 0 if current token is still valid (>5 min left), exit 1 if expired
 *   --force    Regenerate even if token is still valid
 *
 * Requirements: Node.js >= 18 (built-in fetch + crypto)
 */

import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { createSign } from "node:crypto";
import { resolve, dirname } from "node:path";
import { homedir } from "node:os";
import { fileURLToPath } from "node:url";

const ROOT        = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SECRETS_DIR = resolve(ROOT, ".secrets");
const CONFIG_PATH = resolve(SECRETS_DIR, "github-app.json");
const ENV_PATH    = resolve(SECRETS_DIR, ".env");
const MCP_PATH    = resolve(SECRETS_DIR, "mcp-servers.json");
const GH_HOSTS    = resolve(homedir(), ".config/gh/hosts.yml");
const BOT_USER    = "agent-digitals-git-orchestrator[bot]";

const ARGS        = process.argv.slice(2);
const FLAG_CHECK  = ARGS.includes("--check");
const FLAG_FORCE  = ARGS.includes("--force");
const INSTALL_ARG = ARGS.find(a => !a.startsWith("--"));

// ── Token validity check ─────────────────────────────────────
function readCurrentExpiry() {
  if (!existsSync(ENV_PATH)) return null;
  const match = readFileSync(ENV_PATH, "utf8").match(/^# Expires: (.+)$/m);
  return match ? new Date(match[1].trim()) : null;
}

function isTokenValid(expiry, bufferMs = 5 * 60 * 1000) {
  if (!expiry) return false;
  return expiry.getTime() - Date.now() > bufferMs;
}

// ── Load config ──────────────────────────────────────────────
let config;
try {
  config = JSON.parse(readFileSync(CONFIG_PATH, "utf8"));
} catch (err) {
  console.error(`[!] Cannot read ${CONFIG_PATH}: ${err.message}`);
  process.exit(1);
}

const APP_ID     = String(config.app_id || "");
const KEY_PATH   = resolve(ROOT, config.private_key_path || "");
const INSTALL_ID = INSTALL_ARG || config.installation_id || null;

if (!APP_ID || APP_ID === "REPLACE_WITH_YOUR_APP_ID") {
  console.error("[!] Fill in 'app_id' in .secrets/github-app.json first.");
  process.exit(1);
}

// ── --check mode: just report validity ──────────────────────
if (FLAG_CHECK) {
  const expiry = readCurrentExpiry();
  if (isTokenValid(expiry)) {
    const minLeft = Math.round((expiry - Date.now()) / 60000);
    console.log(`[✓] Token valid — ${minLeft} min remaining (expires ${expiry.toISOString()})`);
    process.exit(0);
  } else {
    console.log(`[!] Token expired or missing — regeneration needed`);
    process.exit(1);
  }
}

// ── Skip if still valid (unless --force) ────────────────────
if (!FLAG_FORCE) {
  const expiry = readCurrentExpiry();
  if (isTokenValid(expiry)) {
    const minLeft = Math.round((expiry - Date.now()) / 60000);
    console.log(`[•] Token still valid (${minLeft} min left) — skipping regeneration. Use --force to override.`);
    process.exit(0);
  }
}

let privateKey;
try {
  privateKey = readFileSync(KEY_PATH, "utf8");
} catch (err) {
  console.error(`[!] Cannot read private key at '${KEY_PATH}': ${err.message}`);
  process.exit(1);
}

// ── JWT (RS256) ──────────────────────────────────────────────
function buildJWT(appId, key) {
  const b64url = (v) => Buffer.from(JSON.stringify(v)).toString("base64url");
  const now = Math.floor(Date.now() / 1000);
  const header  = b64url({ alg: "RS256", typ: "JWT" });
  const payload = b64url({ iat: now - 60, exp: now + 540, iss: appId });
  const msg     = `${header}.${payload}`;
  const signer  = createSign("RSA-SHA256");
  signer.update(msg);
  return `${msg}.${signer.sign(key, "base64url")}`;
}

// ── GitHub API ───────────────────────────────────────────────
async function ghApi(path, jwt, method = "GET") {
  const res = await fetch(`https://api.github.com${path}`, {
    method,
    headers: {
      Authorization: `Bearer ${jwt}`,
      Accept: "application/vnd.github+json",
      "X-GitHub-Api-Version": "2022-11-28",
      "User-Agent": "agency-agents/1.0",
    },
  });
  if (!res.ok) throw new Error(`${method} ${path} → ${res.status}: ${await res.text()}`);
  return res.json();
}

// ── Writers ──────────────────────────────────────────────────

function writeEnv(token, expiresAt, installId) {
  writeFileSync(ENV_PATH, [
    `# Auto-generated by scripts/github-app-token.js`,
    `# Expires: ${expiresAt}`,
    `GITHUB_TOKEN=${token}`,
    `GITHUB_APP_ID=${APP_ID}`,
    `GITHUB_APP_INSTALLATION_ID=${installId}`,
    "",
  ].join("\n"));
  console.log(`[✓] Written: .secrets/.env`);
}

function writeMcpServers(token) {
  writeFileSync(MCP_PATH, JSON.stringify({
    mcpServers: {
      github: {
        command: "npx",
        args: ["-y", "@github/github-mcp-server"],
        env: { GITHUB_PERSONAL_ACCESS_TOKEN: token },
      },
    },
  }, null, 2) + "\n");
  console.log(`[✓] Written: .secrets/mcp-servers.json`);
}

function writeGhHosts(token) {
  // Write directly — no gh CLI command needed
  const yaml = [
    `github.com:`,
    `    users:`,
    `        ${BOT_USER}:`,
    `            oauth_token: ${token}`,
    `    user: ${BOT_USER}`,
    `    oauth_token: ${token}`,
    ``,
  ].join("\n");

  const dir = resolve(homedir(), ".config/gh");
  if (!existsSync(dir)) mkdirSync(dir, { recursive: true });
  writeFileSync(GH_HOSTS, yaml);
  console.log(`[✓] Written: ~/.config/gh/hosts.yml`);
}

// ── Main ─────────────────────────────────────────────────────
async function main() {
  console.log(`[•] Generating JWT for App ID ${APP_ID}...`);
  const jwt = buildJWT(APP_ID, privateKey);

  let installId = INSTALL_ID;
  if (!installId) {
    console.log("[•] Fetching installations...");
    const installs = await ghApi("/app/installations", jwt);
    if (!installs.length) {
      console.error("[!] No installations found.");
      process.exit(1);
    }
    installId = installs[0].id;
    console.log(`[✓] Using installation ${installId} (${installs[0].account?.login})`);
    config.installation_id = installId;
    writeFileSync(CONFIG_PATH, JSON.stringify(config, null, 2) + "\n");
  }

  console.log("[•] Requesting installation access token...");
  const { token, expires_at } = await ghApi(
    `/app/installations/${installId}/access_tokens`,
    jwt,
    "POST"
  );
  console.log(`[✓] Token obtained — expires at ${expires_at}\n`);

  // ── Inject into all channels ─────────────────────────────
  console.log("[•] Injecting token into all channels...");
  writeEnv(token, expires_at, installId);
  writeMcpServers(token);
  writeGhHosts(token);

  // ── Summary ──────────────────────────────────────────────
  const expiryLocal = new Date(expires_at).toLocaleTimeString();
  const minsLeft = Math.round((new Date(expires_at) - Date.now()) / 60000);

  console.log("\n┌──────────────────────────────────────────────────┐");
  console.log("│  GitHub App Token — Injected to all channels     │");
  console.log("├──────────────────────────────────────────────────┤");
  console.log(`│  App ID        : ${String(APP_ID).padEnd(31)} │`);
  console.log(`│  Install ID    : ${String(installId).padEnd(31)} │`);
  console.log(`│  Expires       : ${(expiryLocal + ` (~${minsLeft}min)`).padEnd(31)} │`);
  console.log("├──────────────────────────────────────────────────┤");
  console.log("│  Channels updated:                               │");
  console.log("│    ✓ .secrets/.env                               │");
  console.log("│    ✓ .secrets/mcp-servers.json                   │");
  console.log("│    ✓ ~/.config/gh/hosts.yml                      │");
  console.log("└──────────────────────────────────────────────────┘");
}

main().catch((err) => {
  console.error(`[!] Fatal: ${err.message}`);
  process.exit(1);
});
